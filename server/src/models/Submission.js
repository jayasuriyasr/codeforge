'use strict';

const mongoose = require('mongoose');

// ── State machine (v4) ───────────────────────────────────────────────────────
// `status` is the lifecycle. `verdict` is the result. `error` is infra detail.
//
//   status:  QUEUED → COMPILING → RUNNING → DONE      (verdict is set)
//                                         ↘ ERROR     (verdict stays null, error set)
//
//   verdict: AC | WA | TLE | MLE | RE | CE            (null until DONE; null on ERROR)
//
//   terminal ⇔ status ∈ { DONE, ERROR }
//
// An infra fault (sandbox vanished, daemon error, pool exhausted) is ERROR — it
// is an operator signal, never a contestant verdict.

const STATUS_ENUM = ['QUEUED', 'COMPILING', 'RUNNING', 'DONE', 'ERROR'];
const VERDICT_ENUM = ['AC', 'WA', 'TLE', 'MLE', 'RE', 'CE'];
const TERMINAL_STATUS = ['DONE', 'ERROR'];

const LANGUAGE_ENUM = ['c', 'cpp', 'java', 'python', 'javascript'];

// ── Per-test-case result sub-schema ─────────────────────────────────────────
const testResultSchema = new mongoose.Schema(
  {
    testCaseIndex: { type: Number, required: true },
    verdict:       { type: String, enum: ['AC', 'WA', 'TLE', 'MLE', 'RE'] },
    runtimeMs:     { type: Number },   // actual wall-clock ms for this test case
    memoryMB:      { type: Number },   // peak memory for this test case
    stdout:        { type: String, maxlength: 65536 },  // capped — not storing huge outputs
    stderr:        { type: String, maxlength: 8192 },
  },
  { _id: false }
);

// ── Main schema ──────────────────────────────────────────────────────────────

const submissionSchema = new mongoose.Schema(
  {
    // Idempotent _id set by the API route so duplicate HTTP retries are safe.
    // The route catches Mongo error code 11000 and swallows it.
    _id: {
      type:    String,
      required: true,
    },

    userId: {
      type:     mongoose.Schema.Types.ObjectId,
      ref:      'User',
      required: true,
    },

    problemId: {
      type:     mongoose.Schema.Types.ObjectId,
      ref:      'Problem',
      required: true,
    },

    // Nullable: null when the eligibility middleware demoted a contest submission
    // to casual practice, or when submitted outside any contest.
    contestId: {
      type:    mongoose.Schema.Types.ObjectId,
      ref:     'Contest',
      default: null,
    },

    code: {
      type:      String,
      required:  true,
      maxlength: 200_000,   // ~200 KB cap (matches the route body limit)
    },

    language: {
      type:     String,
      enum:     LANGUAGE_ENUM,
      required: true,
    },

    status: {
      type:    String,
      enum:    STATUS_ENUM,
      default: 'QUEUED',
    },

    // The result. null until status === 'DONE'. Stays null on ERROR.
    verdict: {
      type:    String,
      enum:    [...VERDICT_ENUM, null],
      default: null,
    },

    // Infra-fault detail, set only when status === 'ERROR'.
    error: {
      type: String,
      maxlength: 2048,
      default: null,
    },

    // Contest submission that has so far only been judged on pretests. The
    // post-contest system-test pass re-judges these on the full set and clears
    // the flag. Practice + non-pretest contest submissions are never provisional.
    provisional: {
      type: Boolean,
      default: false,
    },

    // Aggregate timing / memory across all test cases (worst-case)
    runtimeMs: { type: Number },
    memoryMB:  { type: Number },

    // Compile error output (CE only)
    compileError: { type: String, maxlength: 8192 },

    // Per-test-case breakdown (populated by the worker)
    testResults: {
      type:    [testResultSchema],
      default: [],
    },

    // Extracted details for the specific test case that failed
    failedTestCase: {
      input: { type: String, maxlength: 65536 },
      expectedOutput: { type: String, maxlength: 65536 },
      actualOutput: { type: String, maxlength: 65536 },
    },
  },
  {
    timestamps: true,   // createdAt = submission time, updatedAt = verdict time
    // Ensure _id is honoured as-is (not auto-generated by Mongoose when set)
    _id: false,
  }
);

// ── Indexes ──────────────────────────────────────────────────────────────────
// Most common query patterns:
submissionSchema.index({ userId: 1, createdAt: -1 });         // "my submissions"
submissionSchema.index({ problemId: 1, userId: 1 });           // "solved by user"
submissionSchema.index({ contestId: 1, userId: 1, verdict: 1 }); // leaderboard scoring

module.exports = mongoose.model('Submission', submissionSchema);
module.exports.STATUS_ENUM     = STATUS_ENUM;
module.exports.VERDICT_ENUM    = VERDICT_ENUM;
module.exports.TERMINAL_STATUS = TERMINAL_STATUS;
module.exports.LANGUAGE_ENUM   = LANGUAGE_ENUM;
